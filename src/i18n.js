const fragments = Object.entries(tamil)
  .filter(([english]) => english.length > 2 && !/^[a-z]+$/i.test(english))
  .sort(([a], [b]) => b.length - a.length);
const cityNames = [
  "Kanyakumari","Tiruvannamalai","Virudhachalam","Rameshwaram","Chidambaram",
  "Coimbatore","Pondicherry","Tirunelveli","Kumbakonam","Karaikudi",
  "Villupuram","Thanjavur","Velankanni","Cuddalore","Kodaikanal",
  "Bangalore","Madurai","Neyveli","Chennai","Trichy","Salem","Erode",
  "Panruti","Vadalur","Ooty"
];

export function translate(lang, value) {
  if (lang !== "ta" || typeof value !== "string") return value;
  const trimmed = value.trim();
  if (!trimmed) return value;
  let result = tamil[trimmed];
  if (!result) {
    result = trimmed;
    for (const city of cityNames) {
      result = result.replaceAll(city, tamil[city]);
    }
    for (const [english, tamilText] of fragments) {
      result = result.replaceAll(english, tamilText);
    }
  }
  return value.slice(0, value.indexOf(trimmed)) + result + value.slice(value.indexOf(trimmed) + trimmed.length);
}
